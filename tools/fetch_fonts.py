"""Download the site's fonts from Google Fonts into assets/fonts/ and write css/fonts.css.

    python tools/fetch_fonts.py

Fonts (all variable, SIL Open Font License):
  Archivo           display and UI   italic + roman, weight 100-900, width 62-125
  Instrument Sans   body text        italic + roman, weight 400-700, width 75-100
  IBM Plex Mono     typed roles line and game telemetry

Only the "latin" subset is kept. It covers French (accents, oe ligature, quotes, euro sign).
The site then makes no request to Google at all.
"""
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
API = (
    "https://fonts.googleapis.com/css2"
    "?family=Archivo:ital,wdth,wght@0,62..125,100..900;1,62..125,100..900"
    "&family=Instrument+Sans:ital,wdth,wght@0,75..100,400..700;1,75..100,400..700"
    "&family=IBM+Plex+Mono:wght@400;500;600"
    "&display=swap"
)
FILE_NAMES = {
    ("Archivo", "normal"): "Archivo-latin.woff2",
    ("Archivo", "italic"): "Archivo-Italic-latin.woff2",
    ("Instrument Sans", "normal"): "InstrumentSans-latin.woff2",
    ("Instrument Sans", "italic"): "InstrumentSans-Italic-latin.woff2",
}


def get(url, binary=False):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


def main():
    css = get(API)
    blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
    FONTS.mkdir(parents=True, exist_ok=True)
    out = ["/* Generated by tools/fetch_fonts.py. Self-hosted fonts (latin subset), no requests to Google. */\n"]
    for subset, block in blocks:
        if subset != "latin":
            continue
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        weight = re.search(r"font-weight:\s*([\d ]+)", block).group(1).strip()
        stretch = re.search(r"font-stretch:\s*([\d% ]+)", block)
        url = re.search(r"url\((https://[^)]+)\)", block).group(1)
        urange = re.search(r"unicode-range:\s*([^;]+);", block).group(1)
        name = FILE_NAMES.get((family, style)) or f"{family.replace(' ', '')}-{weight.replace(' ', '-')}-latin.woff2"
        (FONTS / name).write_bytes(get(url, binary=True))
        lines = [
            "@font-face {",
            f"  font-family: '{family}';",
            f"  font-style: {style};",
            f"  font-weight: {weight};",
        ]
        if stretch:
            lines.append(f"  font-stretch: {stretch.group(1).strip()};")
        lines += [
            "  font-display: swap;",
            f"  src: url('../assets/fonts/{name}') format('woff2');",
            f"  unicode-range: {urange};",
            "}",
            "",
        ]
        out.append("\n".join(lines))
        print(f"{name}: {(FONTS / name).stat().st_size // 1024} KB")
    (ROOT / "css" / "fonts.css").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
