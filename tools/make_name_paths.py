"""Write js/hero-outlines.js: the outlines of the letters the hero name shows, taken from the site's own font.

The hero draws a line that runs around every letter, including the letters that scroll past when the pointer leaves
the name (css/hero.css .trace, js/home.js adds one svg to each letter). CSS cannot dash text, so the line needs the
real glyph outlines. This reads assets/fonts/Archivo-Italic-latin.woff2, fixes it at the weight and width the hero
uses (800, 125%) and writes one path per letter in font units, y flipped so the baseline is at y = 0.

    python tools/make_name_paths.py            # write js/hero-outlines.js
    python tools/make_name_paths.py --info     # print the font metrics only

Letters: IMANE plus the letters of the scroll (POOL, the same list js/ and index.html use for the fillers).
"""
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "assets/fonts/Archivo-Italic-latin.woff2"
OUT = ROOT / "js/hero-outlines.js"
LETTERS = "IMANE" + "STRKQZXWBMGP"  # the name, then the filler letters of the scroll
WEIGHT, WIDTH = 800, 125


def load():
    font = TTFont(FONT)
    axes = {a.axisTag: (a.minValue, a.defaultValue, a.maxValue) for a in font["fvar"].axes}
    pins = {tag: v for tag, v in (("wght", WEIGHT), ("wdth", WIDTH)) if tag in axes}
    return instancer.instantiateVariableFont(font, pins), axes


def main():
    font, axes = load()
    upem = font["head"].unitsPerEm
    hhea, os2 = font["hhea"], font["OS/2"]
    if "--info" in sys.argv:
        print("axes", axes)
        print("upem", upem, "hhea", hhea.ascent, hhea.descent, hhea.lineGap, "typo", os2.sTypoAscender, os2.sTypoDescender,
              "win", os2.usWinAscent, os2.usWinDescent, "useTypo", bool(os2.fsSelection & 128))
        return
    asc, desc = hhea.ascent, -hhea.descent  # the viewBox covers the line box the browser uses
    glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    rows = []
    for ch in dict.fromkeys(LETTERS):
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # y up becomes negative
        rows.append(f'  {ch}: [{hmtx[name][0]}, "{pen.getCommands()}"],')
    OUT.write_text(
        "// Generated by tools/make_name_paths.py. Outlines of the hero name letters (Archivo Italic 800, width 125%),\n"
        "// font units with the baseline at y = 0: letter: [advance, path]. The hero draws a running line on them.\n"
        f"window.HERO_OUTLINES = {{ ascent: {asc}, descent: {desc}, glyphs: {{\n" + "\n".join(rows) + "\n} };\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: {len(dict.fromkeys(LETTERS))} letters, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
